

/* 
 Static type language:

    In statically typed languages, the type of a variable is known at compile time.
    You must declare the type explicitly 
    Once declared, the variable cannot change its type.
    Example languages: TypeScript, Java, C++.

Dynamic type language:
    In dynamically typed languages, the type of a variable is determined at runtime.
    Variables can change types during execution.
    Example languages: JavaScript, Python.
*/








