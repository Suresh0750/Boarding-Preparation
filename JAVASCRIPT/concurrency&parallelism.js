/* 

    Concurrency and Parallelism

    Concurrency refers to the ability of a system to handle multiple tasks at once but not necessarily simultaneously. Instead, it manages tasks by interleaving or switching between them efficiently. This gives the illusion that tasks are running in parallel, but they are actually being processed one at a time, often in short bursts.

    Parallelism

    Parallelism, on the other hand, refers to the actual simultaneous execution of multiple tasks at the same time. In parallelism, the tasks are split and processed on multiple processors or cores concurrently.
*/